// A small hand-rolled icon set — stroke-based, currentColor, no
// external icon library — replacing the plain text glyphs (↑ ↓ × ▶ ⏸
// ‹ ›) that were scattered across the dashboard and public renderer.
// Every icon shares the same viewBox/stroke weight so they read as
// one consistent system wherever they're dropped in.
import type { SVGProps } from "react";

type IconProps = SVGProps<SVGSVGElement> & { size?: number };

function base({ size = 16, ...props }: IconProps) {
  return {
    width: size,
    height: size,
    viewBox: "0 0 24 24",
    fill: "none",
    stroke: "currentColor",
    strokeWidth: 2,
    strokeLinecap: "round" as const,
    strokeLinejoin: "round" as const,
    ...props,
  };
}

